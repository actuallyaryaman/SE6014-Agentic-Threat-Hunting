"""Write the sample reports under docs/group_C/ (run from the repo root).

    python -m tests.group_C.c3.make_reports

* sample_reports/         the four simulated hunts, verified over a mock Elasticsearch (HTTP)
* sample_reports_c2_runs/   C2's two real runs, then the seven tampered copies, verified against the recording
"""

from __future__ import annotations

import asyncio
import tempfile
from pathlib import Path

from group_C.threat_hunting.evidence import ESGateway, PdfUnavailable, build_report_async, run_with_gateway, write_report
from group_C.threat_hunting.evidence.contracts import HuntBundle, bundle_from_run_dir
from group_C.threat_hunting.evidence.gateways import ReadOnlyES

from .fixture_builder import FIXTURE_DIR
from .recorded_gateway import RUN_IDS, RecordedGateway, load_run
from .servers import MockES
from .tamper import CASES, write_case

DOCS = Path("docs/group_C")


def simulated_hunts() -> None:
    out = DOCS / "sample_reports"
    for path in sorted(FIXTURE_DIR.glob("hunt_bundle_*.json")):
        bundle = HuntBundle.model_validate_json(path.read_text(encoding="utf-8"))
        with MockES() as es:
            report = asyncio.run(run_with_gateway(bundle, ESGateway(ReadOnlyES(url=es.url))))
        write_report(report, out)
        print(f"{report.run_id:22} {report.decision.verdict} ({report.decision.confidence})")


def c2_runs() -> None:
    out = DOCS / "sample_reports_c2_runs"
    rows = ["| Report | Run | Planted error | C2 said | C3 final | C3 review |", "|---|---|---|---|---|---|"]
    for run_id in RUN_IDS:
        truth = load_run(run_id)
        report = asyncio.run(build_report_async(truth, RecordedGateway(truth)))
        write_report(report, out / "original", ("json", "md", "html", "pdf"))
        rows.append(f"| [{run_id}](original/hunt_report_{run_id}.html) | {run_id} | none (untouched) | "
                    f"{report.decision.review.c2_label} ({report.decision.review.c2_confidence}) | "
                    f"{report.decision.verdict} ({report.decision.confidence}) | {report.decision.review.outcome} |")
    with tempfile.TemporaryDirectory() as tmp:
        for case in CASES:
            bundle = bundle_from_run_dir(*write_case(case, Path(tmp)))
            bundle = bundle.model_copy(update={"run_id": f"{bundle.run_id}--{case.name}"})
            report = asyncio.run(build_report_async(bundle, RecordedGateway(load_run(case.run_id))))
            write_report(report, out / "tampered")
            rows.append(f"| [{case.name}](tampered/hunt_report_{bundle.run_id}.html) | {case.run_id} | {case.what} | "
                        f"{report.decision.review.c2_label} ({report.decision.review.c2_confidence}) | "
                        f"{report.decision.verdict} ({report.decision.confidence}) | {report.decision.review.outcome} |")
    (out / "README.md").write_text(
        "# C3 reports on C2's real runs\n\n"
        "Generated by `python -m tests.group_C.c3.make_reports`. `original/` holds the two untouched runs; "
        "`tampered/` holds copies with one planted error each (see `tests/group_C/c3/c2_runs/README.md`).\n"
        "The log store is a recording of the run itself (`RecordedGateway`), not a live Elasticsearch.\n\n"
        + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    simulated_hunts()
    c2_runs()
